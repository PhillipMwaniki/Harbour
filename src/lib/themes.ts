import type { ITheme } from "@xterm/xterm";

/**
 * A theme covers both the terminal palette and the app chrome, so switching
 * theme changes the whole window rather than leaving a dark UI wrapped around a
 * light terminal.
 *
 * `ui` tokens are published as CSS custom properties (`--hb-*`) by the settings
 * store; components reference them through Tailwind arbitrary values.
 */
export interface Theme {
  id: string;
  label: string;
  kind: "dark" | "light";
  ui: {
    /** Window background, behind the terminal. */
    bg: string;
    /** Tab bar, menus, dialogs. */
    panel: string;
    /** Hover state on panel surfaces. */
    hover: string;
    border: string;
    fg: string;
    fgMuted: string;
    accent: string;
    danger: string;
  };
  xterm: ITheme;
}

function theme(
  id: string,
  label: string,
  kind: "dark" | "light",
  ui: Theme["ui"],
  xterm: ITheme,
): Theme {
  return { id, label, kind, ui, xterm };
}

